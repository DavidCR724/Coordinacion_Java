CREATE TYPE ROLES AS ENUM('ESTUDIANTE', 'COORDINADOR', 'ADMINISTRADOR');
	
CREATE TYPE ESTADO_SOLICITUD AS ENUM ('ENVIADA', 'PROCESANDO', 'RECHAZADA', 'FINALIZADA', 'ESPERA');

CREATE TYPE PRIORIDAD AS ENUM ('BAJA', 'MEDIA', 'ALTA', 'CRITICA');

CREATE TABLE CARRERA (
	ID_CARRERA UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	CLAVE VARCHAR UNIQUE NOT NULL,
	NOMBRE VARCHAR UNIQUE NOT NULL
);

CREATE TABLE USUARIO (
	ID_USUARIO UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	NOMBRES VARCHAR NOT NULL,
	APELLIDO_P VARCHAR NOT NULL,
	APELLIDO_M VARCHAR,
	CORREO VARCHAR NOT NULL UNIQUE,
	ROL ROLES NOT NULL DEFAULT 'ESTUDIANTE',
	ID_CARRERA UUID, 
	NUM_CONTROL VARCHAR UNIQUE,
	SEMESTRE SMALLINT,
	CONSTRAINT CHK_ROL_CARRERA CHECK (
    ROL = 'ADMINISTRADOR'
    OR (ROL = 'COORDINADOR' AND ID_CARRERA IS NOT NULL)
    OR (ROL = 'ESTUDIANTE' AND ID_CARRERA IS NOT NULL AND NUM_CONTROL IS NOT NULL)
	),
	CONSTRAINT FK_CARRERA FOREIGN KEY (ID_CARRERA) REFERENCES CARRERA(ID_CARRERA)
	-- En la coordinación cada carrera tiene asignado un coordinador. Por defecto, todos los temas referentes a coordinación pasan primero por la coordinadora o coordinador de carrera
	-- En algunos casos (sobre todo si se satura una coordinación o es un tema especialmente delicado se refiere a jefatura de coordinación)
	-- Por lo que un coordinador se encarga de una carrera y el jefe de coordinación puede atender a todos
);

CREATE TABLE TRAMITE (
	ID_TRAMITE UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	CLAVE VARCHAR UNIQUE NOT NULL,
	NOMBRE VARCHAR NOT NULL,
	PRIORIDAD PRIORIDAD NOT NULL,
	DESCRIPCION TEXT,
	REQUISITOS TEXT,
	DOC_REQ BOOLEAN NOT NULL DEFAULT FALSE,
	ES_COLECTIVO BOOLEAN NOT NULL DEFAULT FALSE,
	INICIO_PERIODO DATE,
	FIN_PERIODO DATE,
	ACTIVO BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE SOLICITUD (
	ID_SOLICITUD UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	FOLIO INT GENERATED ALWAYS AS IDENTITY UNIQUE,
	ID_TRAMITE UUID NOT NULL,
	ID_SOLICITANTE UUID NOT NULL, -- El ID del alumno que solicita
	ID_ASIGNADO UUID, -- ID del coordinador asignado a la tarea
	ESTADO ESTADO_SOLICITUD NOT NULL DEFAULT 'ENVIADA', 
	PETICION TEXT, -- Un cuerpo de texto que permita hacer una breve explicación de lo que el usuario desea hacer.
	RESOLUCION TEXT, -- Cuerpo de texto que sirve como "Respuesta" por parte del coordinador
	FECHA_REGISTRO TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	FECHA_ACTUALIZACION TIMESTAMPTZ NOT NULL DEFAULT NOW(), 
	CONSTRAINT FK_TRAMITE FOREIGN KEY (ID_TRAMITE) REFERENCES TRAMITE(ID_TRAMITE),
	CONSTRAINT FK_SOLICITANTE FOREIGN KEY(ID_SOLICITANTE) REFERENCES USUARIO(ID_USUARIO),
	CONSTRAINT FK_ASIGNADO FOREIGN KEY (ID_ASIGNADO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE DOCUMENTO_ADJUNTO(
	ID_DOCUMENTO UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	ID_SOLICITUD UUID NOT NULL,
	REFERENCIA VARCHAR NOT NULL, -- RUTA DONDE SE ALMACENE EL DOCUMENTO POR SI SE ALMACENA EN ALGÚN OTRO LADO
	NOMBRE_ORIGINAL VARCHAR NOT NULL, -- NOMBRE ORIGINAL DEL ARCHIVO
	MIME VARCHAR,
	TAMANO_BYTES BIGINT, 
	FECHA_SUBIDA TIMESTAMPTZ NOT NULL DEFAULT NOW(), 
	CONSTRAINT FK_SOLICITUD_DOCUMENTO_ADJUNTO FOREIGN KEY (ID_SOLICITUD) REFERENCES SOLICITUD(ID_SOLICITUD)
);

CREATE TABLE HISTORIAL_SOLICITUD (
	ID_HISTORIAL_SOLICITUD UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	ID_SOLICITUD UUID NOT NULL,
	ESTADO_ANTERIOR ESTADO_SOLICITUD,
	ESTADO_NUEVO ESTADO_SOLICITUD NOT NULL,
	ID_ACTOR UUID NOT NULL,
	COMENTARIO TEXT,
	FECHA TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CONSTRAINT FK_SOLICITUD_HISTORIAL_SOLICITUD FOREIGN KEY (ID_SOLICITUD) REFERENCES SOLICITUD(ID_SOLICITUD),
	CONSTRAINT FK_ACTOR FOREIGN KEY (ID_ACTOR) REFERENCES USUARIO(ID_USUARIO)
);


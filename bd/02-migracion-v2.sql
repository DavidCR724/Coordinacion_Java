-- 1. Funciones de apoyo
-- ---------------------------------------------------------------------
-- Mantiene FECHA_ACTUALIZACION sin depender de que la aplicación lo recuerde.
CREATE OR REPLACE FUNCTION FN_TOCAR_FECHA_ACTUALIZACION() RETURNS TRIGGER AS $$
BEGIN
    NEW.FECHA_ACTUALIZACION := NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- La bitácora de auditoría solo admite inserciones (HU 8.2).
CREATE OR REPLACE FUNCTION FN_AUDITORIA_INMUTABLE() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'La bitácora de auditoría no se puede modificar ni borrar';
END;
$$ LANGUAGE plpgsql;


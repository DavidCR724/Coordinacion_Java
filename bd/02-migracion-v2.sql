-- 10. Vistas para el panel de seguimiento (HU 7.1 a 7.3)
-- ---------------------------------------------------------------------
-- Una fila por solicitud con lo que necesitan los tres paneles.
CREATE VIEW V_SEGUIMIENTO_SOLICITUD AS
SELECT S.ID_SOLICITUD,
       S.FOLIO,
       S.ID_CARRERA,
       C.NOMBRE                                   AS CARRERA,
       T.CLAVE                                    AS CLAVE_TRAMITE,
       T.NOMBRE                                   AS TRAMITE,
       S.ESTADO,
       S.PRIORIDAD,
       S.FECHA_REGISTRO,
       S.FECHA_CIERRE,
       CASE WHEN S.FECHA_CIERRE IS NOT NULL
            THEN S.FECHA_CIERRE - S.FECHA_REGISTRO END AS TIEMPO_RESOLUCION,
       COALESCE(H.ULTIMO_MOVIMIENTO, S.FECHA_REGISTRO)  AS ULTIMO_MOVIMIENTO
FROM SOLICITUD S
JOIN TRAMITE T ON T.ID_TRAMITE = S.ID_TRAMITE
JOIN CARRERA C ON C.ID_CARRERA = S.ID_CARRERA
LEFT JOIN (SELECT ID_SOLICITUD, MAX(FECHA) AS ULTIMO_MOVIMIENTO
           FROM HISTORIAL_SOLICITUD GROUP BY ID_SOLICITUD) H
       ON H.ID_SOLICITUD = S.ID_SOLICITUD;

-- HU 7.3: solicitudes abiertas sin movimiento en más de 5 días.
CREATE VIEW V_SOLICITUD_REZAGADA AS
SELECT V.*, NOW() - V.ULTIMO_MOVIMIENTO AS TIEMPO_SIN_MOVIMIENTO
FROM V_SEGUIMIENTO_SOLICITUD V
WHERE V.ESTADO IN ('ENVIADA', 'PROCESANDO', 'ESPERA')
  AND V.ULTIMO_MOVIMIENTO < NOW() - INTERVAL '5 days';

